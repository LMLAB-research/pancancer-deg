args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
frames <- unlist(lapply(sys.frames(), function(x) x$ofile))
script_file <- if (length(frames)) tail(frames, 1) else if (length(args)) sub("^--file=", "", args[1]) else stop("Source this script or use Rscript.")
script_dir <- dirname(normalizePath(script_file))
.libPaths(c(file.path(script_dir, ".Rlib"), .libPaths()))
source(file.path(script_dir, "config.R"))
source(file.path(script_dir, "prepare_inputs.R"))
source(file.path(script_dir, "helpers.R"))
run_database("MSIGDB")
